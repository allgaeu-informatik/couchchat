#!/usr/bin/env node
// gen-third-party.mjs - generate THIRD_PARTY_LICENSES.md from vendor.lock.json.
// For every npm entry the package is packed (npm pack, same as vendor.mjs), the license field of the packed
// package.json is read and compared with the "license" in the lock; a mismatch aborts (exit 1) so the lock never
// claims a licence the package does not declare. Needs network and npm.
//
//   node scripts/gen-third-party.mjs                 # writes THIRD_PARTY_LICENSES.md
//   node scripts/gen-third-party.mjs --out <file>
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const args = process.argv.slice(2);
const opt = (n, d) => (args.includes(n) ? args[args.indexOf(n) + 1] : d);
const lockPath = path.resolve(opt('--lock', 'vendor.lock.json'));
const outPath = path.resolve(opt('--out', 'THIRD_PARTY_LICENSES.md'));
const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));

const norm = (s) =>
    String(s || '')
        .replace(/[()]/g, '')
        .replace(/\s+/g, ' ')
        .trim()
        .toUpperCase();
const GPL = /GPL/i;
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tpl-'));
const rows = [];
const problems = [];

try {
    for (const e of lock.entries) {
        if (e.type === 'npm') {
            const spec = `${e.package}@${e.version}`;
            const dir = fs.mkdtempSync(path.join(tmp, 'pk-'));
            const meta = JSON.parse(
                execFileSync('npm', ['pack', spec, '--json', '--silent', '--ignore-scripts'], { cwd: dir, encoding: 'utf8', shell: process.platform === 'win32' })
            )[0];
            execFileSync('tar', ['-xzf', meta.filename], { cwd: dir }); // relative path: GNU tar on Windows reads C: as a host
            const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package', 'package.json'), 'utf8'));
            const declared = typeof pj.license === 'string' ? pj.license : pj.license?.type || (pj.licenses || []).map((l) => l.type).join(' OR ');
            const files = fs.readdirSync(path.join(dir, 'package')).filter((f) => /^(licen[sc]e|copying)/i.test(f));
            if (norm(declared) !== norm(e.license)) {
                problems.push(`${spec}: lock says "${e.license}", package.json says "${declared}"`);
            }
            rows.push({ name: e.name, src: `npm ${e.package}`, version: e.version, license: declared || e.license, files: files.join(', ') || '-', gpl: GPL.test(declared || e.license) });
            console.log(`ok ${spec}: ${declared}`);
        } else {
            const hosts = [...new Set(e.files.map((f) => new URL(f.url).host))].join(', ');
            rows.push({ name: e.name, src: `url ${hosts}`, version: '-', license: e.license, files: e.files.map((f) => f.to).join(', '), gpl: GPL.test(e.license) });
            console.log(`ok ${e.name}: ${e.license} (from lock, not verifiable from a package)`);
        }
    }
} finally {
    fs.rmSync(tmp, { recursive: true, force: true });
}
if (problems.length) {
    console.error('gen-third-party: FAIL: licence mismatch:\n  ' + problems.join('\n  '));
    process.exit(1);
}

const esc = (s) => String(s).replace(/\|/g, '\|');
const lines = [
    '# Third-party licences (generated)',
    '',
    'Generated by `node scripts/gen-third-party.mjs` from `vendor.lock.json` and the `license` field of each packed',
    'package.json. Do not edit by hand. These libraries are self-hosted in the image under `/src/public/vendor/`.',
    '',
    '| Name | Source | Version | Licence | Licence files in package |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${esc(r.name)} | ${esc(r.src)} | ${esc(r.version)} | ${esc(r.license)}${r.gpl ? ' **(GPL)**' : ''} | ${esc(r.files)} |`),
    '',
    'Entries marked GPL (GPL-3.0-only as declared by the package) are served unmodified as separate files; their source',
    'is the public npm package named above (GPLv3 section 13 permits the combination with AGPLv3 code, see `NOTICE.md`).',
    'Further components not listed here: the Inter font (SIL OFL 1.1,',
    '`branding/fonts/LICENSE-Inter.txt`) and the MiroTalk P2P code itself (AGPL-3.0).',
    '',
];
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`gen-third-party: wrote ${outPath} (${rows.length} entries)`);
